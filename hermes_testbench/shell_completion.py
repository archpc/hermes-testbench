"""Shell completion generation for the ``testbench`` CLI.

Candidates are derived from the live :func:`hermes_testbench.cli.build_parser`
tree, never from a hand-maintained list, so a new subcommand or flag appears in
the completions without touching this module — a new *positional choice* or a new
non-``path`` file argument does, because only option values are exported. Emitted
scripts must run on the macOS system shells: bash 3.2.57 and zsh 5.9.

Known limits, all consequences of the generated shape rather than bugs to chase:

* both scripts assume the subcommand is word 2 (``testbench <cmd> ...``), so a
  global option before the subcommand (``testbench --home DIR ru<TAB>``) defeats
  command and option completion entirely;
* only positional arguments whose ``dest`` is literally ``path`` get file
  completion, and no positional's ``choices`` are offered as values;
* ``value_choices`` is keyed by option string across the whole tree, so two
  commands declaring the same option name with different choices would collide
  (last one wins); today only ``--format`` and ``--profile`` carry choices.

Generation reaches into argparse internals (``_actions``, ``_choices_actions``,
``choices``) because argparse exposes no public tree walk. That is the reason the
tests pin the *output* on real shells instead of trusting the introspection alone:
a Python release that renames those internals breaks generation, not the scripts
already installed.

Installation is opt-in and never performed here: the user redirects the printed
script into an ``fpath``/bash-completion directory (see README).
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from typing import Dict, List, Tuple

from .schema import ProfileName

GENERATED_MARKER = "generated by `testbench completion"

# ``--profile`` has no argparse ``choices`` (it is validated downstream), so it
# is sourced from the schema, the single definition of the profile names.
_PROFILE_CHOICES: Tuple[str, ...] = tuple(ProfileName.STANDARD)


@dataclass
class CommandSpec:
    """Flattened view of one argparse parser, as the script templates need it.

    ``options`` keeps declaration order (help first, because argparse adds
    ``-h/--help`` first) and includes every visible option string. ``value_choices``
    maps an *option string* to its fixed values; ``path_positional`` means "this
    command takes a directory and should offer files when the cursor is not on a
    dash". ``subcommands`` preserves parser order, which is what makes the emitted
    ``case`` blocks deterministic across runs.
    """

    name: str
    help: str
    options: List[str] = field(default_factory=list)
    value_choices: Dict[str, Tuple[str, ...]] = field(default_factory=dict)
    path_positional: bool = False
    subcommands: Dict[str, "CommandSpec"] = field(default_factory=dict)


def _subparser_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _is_hidden(action: argparse.Action) -> bool:
    return action.help is argparse.SUPPRESS or bool(getattr(action, "hidden", False))


def _choice_help(action: argparse._SubParsersAction) -> Dict[str, str]:
    return {
        pseudo.dest: str(pseudo.help or "")
        for pseudo in (getattr(action, "_choices_actions", None) or [])
        if pseudo.dest and pseudo.help is not argparse.SUPPRESS
    }


def _hidden_choices(action: argparse._SubParsersAction) -> set[str]:
    return {
        pseudo.dest
        for pseudo in (getattr(action, "_choices_actions", None) or [])
        if pseudo.dest and pseudo.help is argparse.SUPPRESS
    }


def _command_spec(name: str, parser: argparse.ArgumentParser, help_text: str = "") -> CommandSpec:
    """Collect one parser's visible options, value choices, and children.

    Only ``option_strings`` are inspected for values, so positional ``choices``
    (``completion bash|zsh``) never reach the scripts. ``--profile`` is special
    cased because it carries no argparse ``choices`` by design. A positional whose
    ``dest`` is ``path`` sets ``path_positional``; other positionals (``run_id``,
    ``tape_file``, ``evidence_or_run_id``) are invisible to completion, which is
    why ``tape run <TAB>`` offers nothing.
    """
    spec = CommandSpec(name=name, help=help_text)
    for arg in parser._actions:
        if isinstance(arg, argparse._SubParsersAction):
            continue
        if arg.option_strings:
            if _is_hidden(arg):
                continue
            spec.options.extend(arg.option_strings)
            if isinstance(arg.choices, (list, tuple)):
                values = tuple(str(v) for v in arg.choices)
                for opt in arg.option_strings:
                    spec.value_choices[opt] = values
            elif arg.dest == "profile":
                for opt in arg.option_strings:
                    spec.value_choices[opt] = _PROFILE_CHOICES
        elif arg.dest == "path":
            spec.path_positional = True

    action = _subparser_action(parser)
    if action is not None:
        helps = _choice_help(action)
        hidden = _hidden_choices(action)
        for sub_name, sub_parser in (getattr(action, "choices", None) or {}).items():
            if sub_name in hidden or not isinstance(sub_parser, argparse.ArgumentParser):
                continue
            spec.subcommands[sub_name] = _command_spec(sub_name, sub_parser, helps.get(sub_name, ""))
    return spec


def command_tree(parser: argparse.ArgumentParser) -> Dict[str, CommandSpec]:
    """Visible top-level commands of ``parser``, in declaration order."""
    action = _subparser_action(parser)
    if action is None:
        return {}
    helps = _choice_help(action)
    hidden = _hidden_choices(action)
    tree: Dict[str, CommandSpec] = {}
    for name, sub in (getattr(action, "choices", None) or {}).items():
        if name in hidden or not isinstance(sub, argparse.ArgumentParser):
            continue
        tree[name] = _command_spec(name, sub, helps.get(name, ""))
    return tree


def top_level_options(parser: argparse.ArgumentParser) -> List[str]:
    opts: List[str] = []
    for arg in parser._actions:
        if isinstance(arg, argparse._SubParsersAction) or not arg.option_strings:
            continue
        if _is_hidden(arg):
            continue
        opts.extend(arg.option_strings)
    return opts


def _all_value_choices(tree: Dict[str, CommandSpec]) -> Dict[str, Tuple[str, ...]]:
    seen: Dict[str, Tuple[str, ...]] = {}
    for spec in tree.values():
        seen.update(spec.value_choices)
        for sub in spec.subcommands.values():
            seen.update(sub.value_choices)
    return seen


def _zsh_quote(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def _zsh_describe(indent: str, title: str, subcommands: Dict[str, CommandSpec]) -> List[str]:
    lines = [f"{indent}local -a cands", f"{indent}cands=("]
    for name, sub in subcommands.items():
        desc = (sub.help or name).replace("'", "").replace("\n", " ")
        lines.append(f"{indent}  {_zsh_quote(f'{name}:{desc}')}")
    lines.append(f"{indent})")
    lines.append(f"{indent}_describe -t commands {_zsh_quote(title)} cands")
    return lines


def _zsh_options(indent: str, spec: CommandSpec) -> List[str]:
    options = " ".join(spec.options)
    if not spec.path_positional:
        return [f"{indent}compadd -- {options}"]
    return [
        f"{indent}if [[ $cur == -* ]]; then",
        f"{indent}  compadd -- {options}",
        f"{indent}else",
        f"{indent}  _files -/",
        f"{indent}fi",
    ]


def render_zsh(parser: argparse.ArgumentParser) -> str:
    """Emit a ``#compdef`` script for zsh 5.9.

    Shape: first handle "we are completing an option value" from ``prev``, then
    the command position (``CURRENT == 2``) with top-level options plus described
    commands, then a ``case`` per command. ``words[1]`` is the program in zsh, so
    ``words[2]`` is the subcommand — the script has no notion of options before it.

    Option values are emitted as an unconditional ``compadd`` keyed only on
    ``prev``, so a same-named option in a different command inherits the same
    candidates. Leaf subcommands with no options are skipped inside the ``case``:
    an empty branch would end the function with no candidates instead of letting
    the parent's completion stand.
    """
    tree = command_tree(parser)
    out: List[str] = [
        "#compdef testbench",
        f"# {GENERATED_MARKER} zsh`; do not edit.",
        "",
        "local cur prev cmd sub",
        "cur=${words[CURRENT]}",
        "prev=${words[CURRENT-1]}",
        "cmd=${words[2]}",
        "",
        "# fixed-choice option values",
        "case $prev in",
    ]
    for opt, values in _all_value_choices(tree).items():
        out.append(f"  ({opt}) compadd -- {' '.join(values)}; return 0 ;;")
    out += [
        "esac",
        "",
        "if (( CURRENT == 2 )); then",
        f"  compadd -- {' '.join(top_level_options(parser))}",
        *_zsh_describe("  ", "testbench command", tree),
        "  return 0",
        "fi",
        "",
        "case $cmd in",
    ]
    for name, spec in tree.items():
        out.append(f"  ({name})")
        if spec.subcommands:
            out += [
                "    if (( CURRENT == 3 )); then",
                *_zsh_describe("      ", f"testbench {name}", spec.subcommands),
                "      return 0",
                "    fi",
                "    sub=${words[3]}",
                "    case $sub in",
            ]
            for sub_name, sub_spec in spec.subcommands.items():
                if not sub_spec.options:
                    continue
                out.append(f"      ({sub_name})")
                out += _zsh_options("        ", sub_spec)
                out.append("        ;;")
            out += ["    esac", "    ;;"]
        else:
            out += _zsh_options("    ", spec)
            out.append("    ;;")
    out += ["esac", "return 0", ""]
    return "\n".join(out)


def _bash_options(indent: str, spec: CommandSpec) -> List[str]:
    options = " ".join(spec.options)
    if not spec.path_positional:
        return [f'{indent}COMPREPLY=( $(compgen -W "{options}" -- "$cur") )']
    return [
        f'{indent}if [ "${{cur:0:1}}" = "-" ]; then',
        f'{indent}  COMPREPLY=( $(compgen -W "{options}" -- "$cur") )',
        f"{indent}else",
        f'{indent}  COMPREPLY=( $(compgen -d -- "$cur") )',
        f"{indent}fi",
    ]


def render_bash(parser: argparse.ArgumentParser) -> str:
    """Emit a bash-3.2-compatible completion function for ``testbench``.

    bash 3.2 is the macOS system shell, so: no associative arrays, no ``mapfile``,
    no ``local -n``. ``COMP_WORDS[1]`` is assumed to be the subcommand (the
    program name is word 0), and the top-level branch triggers only at
    ``COMP_CWORD == 1`` — which means a root option before the subcommand lands in
    the ``case "$cmd"`` default and yields no candidates at all.

    Directory completion is offered only for ``path_positional`` commands and only
    when the current word does not start with ``-``, so flags still complete for
    ``run``/``discover``/``trust``.
    """
    tree = command_tree(parser)
    out: List[str] = [
        "# bash completion for testbench",
        f"# {GENERATED_MARKER} bash`; do not edit.",
        "# bash 3.2 compatible (macOS /bin/bash): no associative arrays.",
        "",
        "_testbench() {",
        "  local cur prev cmd sub",
        "  COMPREPLY=()",
        '  cur="${COMP_WORDS[COMP_CWORD]}"',
        '  prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '  cmd="${COMP_WORDS[1]}"',
        "",
        '  case "$prev" in',
    ]
    for opt, values in _all_value_choices(tree).items():
        joined = " ".join(values)
        out.append(f'    {opt}) COMPREPLY=( $(compgen -W "{joined}" -- "$cur") ); return 0 ;;')
    out += [
        "  esac",
        "",
        '  if [ "$COMP_CWORD" -eq 1 ]; then',
        f'    COMPREPLY=( $(compgen -W "{" ".join(tree)}" -- "$cur") )',
        "    return 0",
        "  fi",
        "",
        '  case "$cmd" in',
    ]
    for name, spec in tree.items():
        out.append(f"    {name})")
        if spec.subcommands:
            out += [
                '      if [ "$COMP_CWORD" -eq 2 ]; then',
                f'        COMPREPLY=( $(compgen -W "{" ".join(spec.subcommands)}" -- "$cur") )',
                "        return 0",
                "      fi",
                '      sub="${COMP_WORDS[2]}"',
                '      case "$sub" in',
            ]
            for sub_name, sub_spec in spec.subcommands.items():
                if not sub_spec.options:
                    continue
                out.append(f"        {sub_name})")
                out += _bash_options("          ", sub_spec)
                out.append("          return 0 ;;")
            out += ["      esac", "      ;;"]
        else:
            out += _bash_options("      ", spec)
            out.append("      ;;")
    out += [
        "  esac",
        "  return 0",
        "}",
        "",
        "complete -F _testbench testbench",
        "",
    ]
    return "\n".join(out)


def render(shell: str) -> str:
    """Return the completion script for ``shell`` (``"bash"`` or ``"zsh"``).

    Builds a throwaway parser rather than importing one from a global: completion
    must describe the CLI *this* build ships, including a command added five
    minutes ago. No store, no home, no filesystem access — the CLI surfaces this
    behind ``testbench completion <shell>`` precisely so it can run anywhere.
    """
    from .cli import build_parser

    parser = build_parser()
    if shell == "zsh":
        return render_zsh(parser)
    if shell == "bash":
        return render_bash(parser)
    raise ValueError(f"unsupported shell: {shell!r} (expected 'bash' or 'zsh')")
